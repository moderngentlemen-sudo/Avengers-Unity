using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;
using Reforged.Sim;

/// <summary>
/// Usage: dotnet run --project Tools/FrameData -- [outputDir]
/// Writes Docs/FrameData/&lt;hero_slug&gt;.json (consumed by Tools/Blender/build_proxy_hero.py so
/// animation timing always matches gameplay) and Docs/MoveList.md.
/// </summary>
static class Program
{
    static int Main(string[] args)
    {
        string root = FindRepoRoot();
        string outDir = args.Length > 0 ? args[0] : Path.Combine(root, "Docs", "FrameData");
        Directory.CreateDirectory(outDir);
        var content = GrayboxContent.Create();
        var md = new StringBuilder("# Move List & Frame Data\n\nGenerated by `Tools/FrameData` from the simulation. Frames are 1/60 s.\n");

        foreach (var hero in content.Heroes)
        {
            if (hero.Moves.Count == 0) continue;
            var moves = new List<object>();
            md.Append("\n## ").Append(hero.Name).Append(hero.AssistOnly ? " (assist only)" : "").Append("\n\n");
            md.Append("| Move | Input | Tier | Startup | Active | Recovery | Total | Damage | Juggle | Gauge | Flags |\n|---|---|---|---|---|---|---|---|---|---|---|\n");
            foreach (var m in hero.Moves)
            {
                moves.Add(new
                {
                    name = m.Name, tier = m.Tier.ToString(), input = m.Input.ToString(), direction = m.Direction.ToString(), aerial = m.Aerial,
                    startup = m.Startup, active = m.Active, recovery = m.Recovery, total = m.TotalFrames,
                    activeStart = m.ActiveStart, activeEnd = m.ActiveEnd, damage = m.Damage, flags = m.Flags.ToString(),
                    projectile = m.Projectile != null, selfVelocity = new[] { m.SelfVelocity.X.ToFloat(), m.SelfVelocity.Y.ToFloat() },
                });
                int cost = m.GaugeCost;
                md.Append("| ").Append(m.Name).Append(" | ").Append(Notation(m)).Append(" | ").Append(m.Tier)
                  .Append(" | ").Append(m.Startup).Append(" | ").Append(m.Active).Append(" | ").Append(m.Recovery)
                  .Append(" | ").Append(m.TotalFrames).Append(" | ").Append(m.MaxHits > 1 ? m.MaxHits + "×" + m.Damage : m.Damage.ToString())
                  .Append(" | ").Append(m.JuggleCost).Append(" | ").Append(cost > 0 ? "−" + cost : "+" + m.GaugeGain)
                  .Append(" | ").Append(m.Flags == MoveFlags.None ? "" : m.Flags.ToString()).Append(" |\n");
            }
            if (hero.AssistMoves.Length > 0)
                md.Append("\nAssist callouts: LT = ").Append(hero.AssistMoves[0])
                  .Append(hero.AssistMoves.Length > 1 ? ", LT+→ = " + hero.AssistMoves[1] : "")
                  .Append(hero.AssistMoves.Length > 2 ? ", LT+↓ = " + hero.AssistMoves[2] : "").Append("\n");

            var doc = new { hero = hero.Name, fps = SimConstants.TicksPerSecond, assistOnly = hero.AssistOnly,
                            bodyHeight = hero.Height.ToFloat(), assistMoves = hero.AssistMoves, moves };
            string path = Path.Combine(outDir, Slug(hero.Name) + ".json");
            File.WriteAllText(path, JsonSerializer.Serialize(doc, new JsonSerializerOptions { WriteIndented = true }));
            Console.WriteLine("wrote " + path);
        }
        File.WriteAllText(Path.Combine(root, "Docs", "MoveList.md"), md.ToString());
        Console.WriteLine("wrote Docs/MoveList.md");
        return 0;
    }

    static string Notation(MoveDef m)
    {
        string dir = m.Direction switch { StickDir.Forward => "→", StickDir.Back => "←", StickDir.Up => "↑", StickDir.Down => "↓", _ => "" };
        string button = m.Input switch
        {
            MoveInput.Light => "X", MoveInput.Heavy => "Y", MoveInput.Special => "B", MoveInput.Grab => "RB",
            MoveInput.HeroLight => "RT+X", MoveInput.HeroHeavy => "RT+Y", MoveInput.HeroJump => "RT+A", MoveInput.HeroSpecial => "RT+B",
            MoveInput.Super => "RT+LT", MoveInput.UltimateI => "L3+R3", MoveInput.UltimateII => "RT+L3+R3", _ => "?",
        };
        return (m.Aerial ? "air " : "") + (dir.Length > 0 ? dir + "+" : "") + button;
    }

    public static string Slug(string name) => name.ToLowerInvariant().Replace(' ', '_').Replace("-", "_");

    static string FindRepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null && !Directory.Exists(Path.Combine(dir.FullName, "Assets", "_Project"))) dir = dir.Parent;
        return dir?.FullName ?? Directory.GetCurrentDirectory();
    }
}
